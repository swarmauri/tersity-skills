#!/usr/bin/env python3
"""Dependency-free LOC/SLOC and duplicate-block scanner."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from collections import defaultdict
from dataclasses import asdict, dataclass
from pathlib import Path

LANGUAGES = {
    ".c": ("C", ("//",), (("/*", "*/"),)),
    ".cpp": ("C++", ("//",), (("/*", "*/"),)),
    ".cs": ("C#", ("//",), (("/*", "*/"),)),
    ".css": ("CSS", (), (("/*", "*/"),)),
    ".go": ("Go", ("//",), (("/*", "*/"),)),
    ".html": ("HTML", (), (("<!--", "-->"),)),
    ".java": ("Java", ("//",), (("/*", "*/"),)),
    ".js": ("JavaScript", ("//",), (("/*", "*/"),)),
    ".jsx": ("JavaScript", ("//",), (("/*", "*/"),)),
    ".kt": ("Kotlin", ("//",), (("/*", "*/"),)),
    ".md": ("Markdown", (), (("<!--", "-->"),)),
    ".php": ("PHP", ("//", "#"), (("/*", "*/"),)),
    ".py": ("Python", ("#",), (("'''", "'''"), ('"""', '"""'))),
    ".rb": ("Ruby", ("#",), ()),
    ".rs": ("Rust", ("//",), (("/*", "*/"),)),
    ".scss": ("SCSS", ("//",), (("/*", "*/"),)),
    ".sh": ("Shell", ("#",), ()),
    ".sql": ("SQL", ("--",), (("/*", "*/"),)),
    ".swift": ("Swift", ("//",), (("/*", "*/"),)),
    ".ts": ("TypeScript", ("//",), (("/*", "*/"),)),
    ".tsx": ("TypeScript", ("//",), (("/*", "*/"),)),
    ".vue": ("Vue", ("//",), (("/*", "*/"), ("<!--", "-->"))),
    ".xml": ("XML", (), (("<!--", "-->"),)),
    ".yaml": ("YAML", ("#",), ()),
    ".yml": ("YAML", ("#",), ()),
}
IGNORED_DIRS = {
    ".git",
    ".hg",
    ".mypy_cache",
    ".pytest_cache",
    ".ruff_cache",
    ".svn",
    ".tox",
    ".venv",
    "__pycache__",
    "build",
    "coverage",
    "dist",
    "node_modules",
    "target",
    "vendor",
}
GENERATED_MARKERS = ("@generated", "auto-generated", "autogenerated", "do not edit")


@dataclass
class Counts:
    files: int = 0
    loc: int = 0
    blank: int = 0
    comments: int = 0
    sloc: int = 0

    def add(self, other: Counts) -> None:
        self.files += other.files
        self.loc += other.loc
        self.blank += other.blank
        self.comments += other.comments
        self.sloc += other.sloc


def classify(lines: list[str], suffix: str) -> Counts:
    _, single, blocks = LANGUAGES[suffix]
    result = Counts(files=1, loc=len(lines))
    closing: str | None = None
    for line in lines:
        stripped = line.strip()
        if not stripped:
            result.blank += 1
            continue
        if closing:
            result.comments += 1
            if closing in stripped:
                closing = None
            continue
        if any(stripped.startswith(prefix) for prefix in single):
            result.comments += 1
            continue
        opened = next(((start, end) for start, end in blocks if stripped.startswith(start)), None)
        if opened:
            result.comments += 1
            remainder = stripped[len(opened[0]) :]
            if (opened[0] == opened[1] and opened[1] not in remainder) or (
                opened[0] != opened[1] and opened[1] not in remainder
            ):
                closing = opened[1]
            continue
        result.sloc += 1
    return result


def source_files(root: Path, excludes: set[str]) -> list[Path]:
    found = []
    for path in root.rglob("*"):
        if not path.is_file() or path.suffix.lower() not in LANGUAGES:
            continue
        relative = path.relative_to(root)
        if any(part in IGNORED_DIRS or part in excludes for part in relative.parts):
            continue
        found.append(path)
    return sorted(found)


def normalized(line: str) -> str:
    return re.sub(r"\s+", " ", line.strip())


def duplicate_blocks(files: dict[str, list[str]], block_size: int) -> list[dict[str, object]]:
    blocks: dict[str, list[tuple[str, int]]] = defaultdict(list)
    samples: dict[str, str] = {}
    for path, lines in files.items():
        normalized_lines = [normalized(line) for line in lines]
        for index in range(len(lines) - block_size + 1):
            block = normalized_lines[index : index + block_size]
            if any(not line for line in block):
                continue
            text = "\n".join(block)
            digest = hashlib.sha256(text.encode()).hexdigest()[:16]
            blocks[digest].append((path, index + 1))
            samples[digest] = text[:240]
    findings = []
    for digest, occurrences in blocks.items():
        distinct = {(path, line) for path, line in occurrences}
        if len(distinct) < 2:
            continue
        findings.append(
            {
                "fingerprint": digest,
                "block_sloc": block_size,
                "estimated_excess_sloc": block_size * (len(distinct) - 1),
                "occurrences": [{"path": path, "line": line} for path, line in sorted(distinct)],
                "sample": samples[digest],
            }
        )
    findings.sort(key=lambda item: (-item["estimated_excess_sloc"], item["fingerprint"]))
    return findings[:50]


def scan(root: Path, excludes: set[str], block_size: int) -> dict[str, object]:
    total = Counts()
    by_language: dict[str, Counts] = defaultdict(Counts)
    details = []
    content = {}
    generated = []
    for path in source_files(root, excludes):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        relative = path.relative_to(root).as_posix()
        lines = text.splitlines()
        counts = classify(lines, path.suffix.lower())
        language = LANGUAGES[path.suffix.lower()][0]
        total.add(counts)
        by_language[language].add(counts)
        details.append({"path": relative, "language": language, **asdict(counts)})
        if not any(marker in text[:1000].lower() for marker in GENERATED_MARKERS):
            content[relative] = lines
        else:
            generated.append(relative)
    details.sort(key=lambda item: (-item["sloc"], item["path"]))
    return {
        "schema_version": 1,
        "root": str(root),
        "definitions": {
            "loc": "physical lines in recognized text source files",
            "sloc": "nonblank lines not classified as comment-only by language heuristics",
        },
        "totals": asdict(total),
        "languages": {name: asdict(value) for name, value in sorted(by_language.items())},
        "largest_files": details[:25],
        "duplicate_blocks": duplicate_blocks(content, block_size),
        "generated_files_excluded_from_patterns": generated,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("path", nargs="?", type=Path, default=Path.cwd())
    parser.add_argument("--exclude", action="append", default=[])
    parser.add_argument("--block-size", type=int, default=8)
    parser.add_argument("--output", type=Path)
    args = parser.parse_args()
    if args.block_size < 3:
        parser.error("--block-size must be at least 3")
    report = scan(args.path.resolve(), set(args.exclude), args.block_size)
    rendered = json.dumps(report, indent=2) + "\n"
    if args.output:
        args.output.write_text(rendered, encoding="utf-8")
    else:
        print(rendered, end="")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
